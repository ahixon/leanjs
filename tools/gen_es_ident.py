#!/usr/bin/env python3
"""Generates ES/Unicode/Ident.lean (ID_Start / ID_Continue ranges for ECMAScript identifiers)
from UCD DerivedCoreProperties.txt.

Usage: curl -o third_party/ucd/DerivedCoreProperties.txt \
         https://www.unicode.org/Public/UCD/latest/ucd/DerivedCoreProperties.txt
       python3 tools/gen_es_ident.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "third_party/ucd/DerivedCoreProperties.txt"
OUT = ROOT / "ES/Unicode/Ident.lean"


def ranges(prop, text):
    rs = []
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        cps, p = [x.strip() for x in line.split(";")[:2]]
        if p != prop:
            continue
        if ".." in cps:
            a, b = cps.split("..")
            rs.append((int(a, 16), int(b, 16)))
        else:
            rs.append((int(cps, 16), int(cps, 16)))
    rs.sort()
    merged = []
    for a, b in rs:
        if merged and a <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(b, merged[-1][1]))
        else:
            merged.append((a, b))
    # ASCII is handled by the lexer's fast path; keep only non-ASCII ranges
    return [(max(a, 0x80), b) for a, b in merged if b >= 0x80]


def encode(rs):
    # "start-end," hex pairs, decoded once at initialization
    return ",".join(f"{a:x}-{b:x}" if a != b else f"{a:x}" for a, b in rs)


def chunks(s, n=96):
    return [s[i:i + n] for i in range(0, len(s), n)]


def main():
    text = SRC.read_text()
    version = re.search(r"DerivedCoreProperties-([\d.]+)\.txt", text).group(1)
    out = [
        "/-!",
        "# Unicode ID_Start / ID_Continue (generated by tools/gen_es_ident.py — never edit by hand)",
        "",
        f"From UCD DerivedCoreProperties-{version}.txt. Non-ASCII ranges only (the lexer handles ASCII).",
        "spec: https://tc39.es/ecma262/#sec-names-and-keywords",
        "-/",
        "",
        "namespace ES.Unicode",
        "",
    ]
    for name, prop in (("idStart", "ID_Start"), ("idContinue", "ID_Continue")):
        enc = encode(ranges(prop, text))
        out.append(f"/-- {prop} ranges, encoded as `a-b` / `a` hex items separated by commas. -/")
        out.append(f"def {name}Enc : String :=")
        parts = chunks(enc)
        out.append("  " + " ++\n  ".join(f'"{p}"' for p in parts))
        out.append("")
    OUT.write_text("\n".join(out) + "end ES.Unicode\n")
    print(f"wrote {OUT} (Unicode {version})")


if __name__ == "__main__":
    main()

"""Generates JSProofs/ReactCommitOne.lean (zippy docs/react-proofs.md): `crw_one`, `crw_top` with each field the
render writes stated once. crw_top's premises at `w` repeat the same field under each composed callee's names; this
unifies their variables (values, property flags, and the fibers themselves, through the child links) to a fixpoint,
drops the variables so identified and the premises that become duplicates, and proves it by instantiating crw_top."""
import re, sys
sys.path.insert(0, "tools/react_commit")
from compose import binders, _theorem_header

TF = "JSProofs/ReactCommitTop.lean"
cb = binders(TF, "crw_top")
implicit = {n for n, k, t in cb if k == "{"}

def norm(x):
    while True:
        y = re.sub(r"\((\w+)\)", r"\1", x)
        if y == x: return x
        x = y

def parse(s):
    toks = re.findall(r"\(|\)|[^\s()]+", s); pos = 0
    def seq():
        nonlocal pos; out = []
        while pos < len(toks) and toks[pos] != ")":
            if toks[pos] == "(":
                pos += 1; out.append(seq()); pos += 1
            else:
                out.append(toks[pos]); pos += 1
        return out
    return seq()

def text(t):
    return t if isinstance(t, str) else "(" + " ".join(text(x) for x in t) + ")"

def term(t):  # a subterm as the replacement for a variable
    if isinstance(t, str): return t
    if len(t) == 1: return term(t[0])
    return text(t)

def canon(x):
    def c(t):
        if isinstance(t, list):
            if len(t) == 1: return c(t[0])
            return "(" + " ".join(c(y) for y in t) + ")"
        return t
    return c(parse(x))

V = re.compile(r"(?<![A-Za-z0-9_'.])([A-Za-z_][A-Za-z0-9_']*)(?![A-Za-z0-9_'])")
M = {}
def res(x):
    seen = 0
    while x in M and seen < 50: x = M[x]; seen += 1
    return x
def subst(s):
    def f(m):
        n = m.group(1)
        if n in M:
            r = subst(M[n]); return r if re.fullmatch(r"[\w'.]+", r) else f"({r})"
        return n
    return V.sub(f, s)

def unify(a, b, why):
    if isinstance(b, list) and len(b) == 1: b = b[0]
    if isinstance(a, list) and len(a) == 1: a = a[0]
    if isinstance(b, str) and b in implicit and b not in M:
        ta = term(a)
        if ta != b: M[b] = ta; return True
        return False
    if isinstance(a, str) and a in implicit and a not in M and not isinstance(b, str):
        M[a] = term(b); return True
    if isinstance(a, str) and a in implicit and a not in M and isinstance(b, str) and b != a:
        M[a] = b; return True
    if isinstance(a, list) and isinstance(b, list) and len(a) == len(b):
        ch = False
        for x, y in zip(a, b): ch |= unify(x, y, why)
        return ch
    if text(a) != text(b): print("CONFLICT", why, text(a)[:80], "vs", text(b)[:80])
    return False

AT = re.compile(r"\(w\.objEntry (\w+)\)\.props\.get\? \(\.str (\(JSStr\.ofString \"[\w$]+\"\))\) = (.*)$", re.S)
BW = re.compile(r"bW\[(JSStr\.ofString \"[\w$]+\")\]\? = (.*)$", re.S)
wprem = [n for n, k, t in cb if k == "(" and (re.search(r"(?<![\w'.])w\.objEntry", t) or "bW[" in t)
         and not t.strip().startswith("∀")]
for it in range(20):
    groups, ch = {}, False
    for n, k, t in cb:
        if n not in wprem: continue
        tt = re.sub(r"\s+", " ", norm(subst(t.strip())))
        m = AT.match(tt) or BW.match(tt)
        if not m: continue
        key = m.groups()[:-1]; rhs = parse(m.groups()[-1])
        if key in groups: ch |= unify(groups[key][1], rhs, f"{groups[key][0]}/{n}")
        else: groups[key] = (n, rhs)
    if not ch: break
print("iterations", it, "unified", len(M))
# the statement: binders with M substituted; drop mapped variables and duplicate premises
seen, out_b, dup = {}, [], {}
for n, k, t in cb:
    if n in M: continue
    st = canon(re.sub(r"\s+", " ", norm(subst(t.strip()))))
    if k == "(" and st in seen: dup[n] = seen[st]; continue
    if k == "(": seen[st] = n
    out_b.append((k, f"{k}{n} : {subst(t)}{'}' if k == '{' else ')'}", n))
explicit = [n for k, _, n in out_b if k == "("]
implicits = [n for k, _, n in out_b if k == "{" and n not in ("eng", "σ", "answer")]
out_b = [x for k, x, n in out_b if k == "{"] + [x for k, x, n in out_b if k == "("]
print("binders", len(cb), "->", len(out_b), "; duplicate premises", len(dup))
hdr = _theorem_header(TF, "crw_top")
CALL = subst(hdr[hdr.rindex("WP eng answer"):])
def paren(x): return x if re.fullmatch(r"[\w.']+", x) else "(" + x + ")"
args = " ".join(f"({n} := {paren(subst(M[n]))})" for n in M) + " " + \
       " ".join(f"({n} := {r})" for n, r in dup.items()) + " " + " ".join(f"({n} := {n})" for n in explicit + implicits)
BIND = "\n    ".join(out_b)
out = f'''import JSProofs.ReactCommitTop

/-!
# The click's commit, each field the render writes stated once (zippy docs/react-proofs.md)

`crw_one`: `ReactCommitTop.crw_top` with its copies of the work-in-progress fibers and their fields identified
(generated by `tools/react_commit/gen_crw_one.py`).
-/

open ES ES.M HostRuns Logic
open Std (HashMap)
open ReactFacts (BindIs PropIs SelInfo PropHas)
open ReactFlushMutation (FPRE)
open ReactSpawned (FPS FPA FP1)
open ReactCommitRootFn (FPC)
open ReactCommitEntry (FPE)

namespace ReactCommitOne

section
variable {{eng : Engine}} {{σ : Type}} {{answer : HostAnswer σ}}

set_option maxRecDepth 40000 in
set_option maxHeartbeats 8000000 in
theorem crw_one {BIND} :
    {CALL} :=
  ReactCommitTop.crw_top {args}
end

end ReactCommitOne
'''
open("JSProofs/ReactCommitOne.lean", "w").write(out)
for n in sorted(M): pass

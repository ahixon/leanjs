"""Generates JSProofs/ReactBeforeMutationFull.lean (zippy docs/react-proofs.md): cbm_spec with hasSelectionCapabilities
discharged by hsc_spec (premises S_) and the walk's _complete by cbmc_root (premises C_), each at the call state (its
record the call state's: FB's bindings differ; objects as they were, FB writes no property). getActiveElementDeep stays
a contract."""
import sys
sys.path.insert(0, "tools/react_commit")
from compose import binders, compose, _theorem_header

BM = "JSProofs/ReactBeforeMutation.lean"
SE = "JSProofs/ReactSelection.lean"
fb = binders(BM, "cbm_spec")
drop_outer = {"hHSC", "hCCC", "hHSc", "hCCc", "hf"}
outer = [f"{k}{nm} : {t}{'}' if k == '{' else ')'}" for nm, k, t in fb if nm not in drop_outer]
sb, _ = compose(SE, "hsc_spec", "S_", subst={"fo": "fHS", "t": ".undefined", "E": "E"}, given={},
                drop=("n", "h", "s", "hf", "hlt", "hHI"))
# its premises over frames from its entry state: over frames from cbm's, widened by FB
WID = {"hNN": 2, "hTL": 1, "hCE": 2}
sb = [b.replace("DomRead eng answer HI n s {} E", "DomRead eng answer HI n s (FB d.env) E")
       .replace("∀ w, Frame {} s w →", "∀ w, Frame (FB d.env) s w →") for b in sb]
s_given = " ".join(f"({nm} := fun w' h1 hw' hi => S_{nm} w' h1 (frame_then_empty hw hw') hi)" if a == 2
                   else f"({nm} := fun w' hw' => S_{nm} w' (frame_then_empty hw hw'))" for nm, a in WID.items())
cb, _ = compose(BM, "cbmc_root", "C_", subst={"fo": "fCC", "t": ".undefined", "R": "R", "bG": "bG", "oG": "oG"},
                given={}, drop=("n", "h", "s", "hf", "hlt", "hG", "hGe", "hGN", "hGNv", "hGNm", "bdN"))
extra = ["(hf : 1200 ≤ s.fuel)", "(C_hdenv : C_d.env = d.env)"]
binds = "\n    ".join(outer + sb + cb + extra)
fargs = " ".join(f"({nm} := {nm})" for nm, k, t in fb if nm not in drop_outer and nm not in ("n", "h", "s"))
s_imp = " ".join(f"({nm} := S_{nm})" for nm, k, t in binders(SE, "hsc_spec")
                 if k == "{" and nm not in ("n", "h", "s", "fo", "t", "E"))
c_imp = " ".join(f"({nm} := C_{nm})" for nm, k, t in binders(BM, "cbmc_root")
                 if k == "{" and nm not in ("n", "h", "s", "fo", "t", "R", "bG", "oG", "bdN"))
_h = _theorem_header(BM, "cbm_spec")
POST = _h[_h.rindex("fun v w h' =>") + len("fun v w h' =>"):].strip()
stmt = f"""theorem cbm_full {binds} :
    WP eng answer (n + 2) h (callImpl eng (.obj fo) t #[.obj FR, .obj R, .num lanes]) s fun v w h' =>
      {POST} := by
  refine cbm_spec {fargs} (hf := by omega) (hHSc := ⟨_, S_hk⟩) (hCCc := ⟨_, C_hk⟩) (hHSC := ?hHSC) (hCCC := ?hCCC)
  case hHSC =>
    intro w h1 hw hHI1 hfw
    apply ReactSelection.hsc_spec (s := w) (fo := fHS) (t := .undefined) (E := E) {s_imp}
      (hf := by omega) (hlt := lt_heap_of_frame hw hHSo) (hHI := hHI1) {s_given}
    all_goals rebase_tac hw
  case hCCC =>
    intro w h1 hw hfw hN
    obtain ⟨bw, hdw, hbw⟩ := declLike_frame hw hG hGe
    obtain ⟨bd, hbd, hbv, hbm⟩ := hN bw oG hdw
    refine wp_mono (Q := fun v w' h' => v = .undefined ∧ w.fuel ≤ w'.fuel + 200 ∧ h' = h1 ∧
      Frame ⟨[(C_d.env, JSStr.ofString "nextEffect")], [], false⟩ w w' ∧
      ∃ bm, Scope.declLike? (w'.envEntry C_d.env) = some (bm, oG) ∧
        (∃ bd, bm[JSStr.ofString "nextEffect"]? = some bd ∧ bd.value = some .null) ∧
        ∀ x, x ≠ JSStr.ofString "nextEffect" → bm[x]? = bw[x]?) ?_ ?_
    · apply cbmc_root (s := w) (fo := fCC) (t := .undefined) (R := R) (bG := bw) (oG := oG) (bdN := bd) {c_imp}
        (hf := hfw) (hlt := lt_heap_of_frame hw hCCo) (hG := by rw [C_hdenv]; exact lt_envs_of_frame hw hG)
        (hGe := by rw [C_hdenv]; exact hdw) (hGN := hbd) (hGNv := hbv) (hGNm := hbm)
      all_goals rebase_tac hw
    · rintro v w' h' ⟨rfl, hfu, rfl, hF, bm, hd', ⟨bd', hb', hv'⟩, -⟩
      rw [C_hdenv] at hF hd'
      refine ⟨rfl, hfu, rfl, hF, frame_then_sub hw hF (fun p hp => by simp at hp; simp [hp, FB]) rfl rfl, ?_⟩
      intro bm' o' hd''
      rw [hd'] at hd''
      cases hd''
      exact ⟨bd', hb', hv'⟩
"""
out = f'''import JSProofs.ReactBeforeMutation
import JSProofs.ReactSelection

/-!
# The before-mutation pass with its callees (zippy docs/react-proofs.md)

`cbm_full`: `cbm_spec` with `hasSelectionCapabilities` discharged by `ReactSelection.hsc_spec` and the walk's
`commitBeforeMutationEffects_complete` by `cbmc_root`, at the call states (generated by
`tools/react_commit/gen_cbm_full.py`). `getActiveElementDeep` stays a contract (`hGDC`).
-/

open ES ES.M HostRuns Logic
open Std (HashMap)
open ReactFacts (BindIs)

namespace ReactBeforeMutation

section
variable {{eng : Engine}} {{σ : Type}} {{answer : HostAnswer σ}} {{HI : σ → Prop}}

set_option maxRecDepth 40000 in
set_option maxHeartbeats 8000000 in
{stmt}
end

end ReactBeforeMutation
'''
open("JSProofs/ReactBeforeMutationFull.lean", "w").write(out)
